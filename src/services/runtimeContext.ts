/**
 * Server-generated runtime facts that must accompany every provider request.
 *
 * The model has no clock of its own, so a stale or invented date is a common
 * failure. This block is regenerated per request and appended to the system
 * prompt after the operator instruction. It provides facts only; it does not
 * claim priority over operator instructions and contains no secrets.
 */
export function buildRuntimeContext(now: Date, timezone: string): string {
  const zone = resolveTimezone(timezone);
  const formatter = new Intl.DateTimeFormat("en-GB", {
    timeZone: zone,
    weekday: "long",
    day: "numeric",
    month: "long",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
    hour12: false,
    timeZoneName: "longOffset",
  });

  const parts = formatter.formatToParts(now);
  const value = (type: Intl.DateTimeFormatPartTypes) =>
    parts.find((part) => part.type === type)?.value ?? "";
  const offset = value("timeZoneName").replace("GMT", "UTC") || "UTC";

  return [
    "<get_info>",
    `Current date: ${value("weekday")}, ${value("day")} ${value("month")} ${value("year")}`,
    `Current time: ${value("hour")}:${value("minute")}:${value("second")}`,
    `Timezone: ${zone} (${offset})`,
    `ISO 8601: ${now.toISOString()}`,
    `Unix milliseconds: ${now.getTime()}`,
    "These values are generated by the server for this request.",
    "</get_info>",
  ].join("\n");
}

function resolveTimezone(timezone: string): string {
  const candidate = timezone.trim();
  if (candidate) {
    try {
      new Intl.DateTimeFormat("en-GB", { timeZone: candidate }).format(new Date());
      return candidate;
    } catch {
      // Fall through to UTC: an invalid operator value must not break replies.
    }
  }
  return "UTC";
}
